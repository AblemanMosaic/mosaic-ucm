from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from .canonical import atomic_write, canonical_bytes, commitment, read_json
from .model import COMPONENT_KINDS, FORBIDDEN_KEYS, STATES, UIRefusal, validate_tree


def _keys(value: Any):
    if isinstance(value, dict):
        for key, item in value.items():
            yield str(key).lower()
            yield from _keys(item)
    elif isinstance(value, list):
        for item in value:
            yield from _keys(item)


def validate_library_theme_v02(library: dict[str, Any]) -> dict[str, Any] | None:
    """Validate an optional v0.2 theme and its exact v0.1 token projection."""
    theme = library.get("theme_v02")
    if theme is None:
        return None
    from mosaic_ui_std.theme_v02 import project_to_v01, validate_theme_v02

    validate_theme_v02(theme)
    if library.get("tokens") != project_to_v01(theme)["tokens"]:
        raise UIRefusal("COMPONENT_LIBRARY_THEME_V02_MISMATCH", str(theme.get("theme_id")))
    return theme


def validate_component_library(library: dict[str, Any]) -> dict[str, Any]:
    failures: list[str] = []
    if tuple(library.get("states", ())) != STATES:
        failures.append("STATE_MODEL_MISMATCH")
    components = library.get("components")
    if not isinstance(components, list) or not components:
        failures.append("COMPONENT_LIBRARY_EMPTY")
        components = []
    ids: set[str] = set()
    for component in components:
        component_id = component.get("component_id")
        if not component_id or component_id in ids:
            failures.append(f"COMPONENT_ID_INVALID:{component_id}")
        ids.add(str(component_id))
        if component.get("kind") not in COMPONENT_KINDS:
            failures.append(f"UNKNOWN_COMPONENT_KIND:{component.get('kind')}")
    try:
        validate_library_theme_v02(library)
    except UIRefusal as refusal:
        failures.append(f"THEME_V02:{refusal.code}:{refusal.detail}")
    forbidden = sorted(set(_keys(library)) & FORBIDDEN_KEYS)
    if forbidden:
        failures.append("FORBIDDEN_KEYS:" + ",".join(forbidden))
    if failures:
        raise UIRefusal("COMPONENT_LIBRARY_REFUSED", ";".join(sorted(failures)))
    return {
        "component_count": len(components),
        "component_ids": sorted(ids),
        "disposition": "PASS_LOCAL_CANDIDATE",
    }


def compile_library(source_root: Path, output_root: Path, application_path: Path) -> dict[str, Any]:
    specification = read_json(source_root / "specification.json")
    library = read_json(source_root / "component-library.json")
    application = read_json(application_path)
    library_validation = validate_component_library(library)
    operations = set(application.get("declared_operation_ids", ()))
    tree_validation = validate_tree(application["tree"], operations)
    inputs = {
        "specification": specification,
        "library": library,
        "application": application,
    }
    input_root = commitment("MOSAIC.UI.FOUNDRY.INPUT.v0.1", inputs)
    payload = {
        "schema": "mosaic.ui.generated-library.v0.1",
        "input_root": input_root,
        "specification": specification,
        "library": library,
        "application": application,
        "library_validation": library_validation,
        "tree_validation": tree_validation,
        "realization": {
            "target": "WIN32_CTYPES_NATIVE",
            "browser_intermediary": False,
            "tkinter": False,
            "third_party_packages": [],
            "allowed_effects": ["NATIVE_WINDOW", "LOCAL_INPUT", "LOCAL_DRAW", "SEMANTIC_INTENT"],
            "forbidden_effects": ["NETWORK", "RUNTIME_PACKAGE_ACQUISITION", "GOVERNED_APPLICATION_EFFECT"],
        },
        "standing": "LOCAL_CANDIDATE",
        "authority_effect": "NONE",
    }
    generated_root = commitment("MOSAIC.UI.GENERATED_LIBRARY.v0.1", payload)
    payload_json = json.dumps(payload, ensure_ascii=True, sort_keys=True, separators=(",", ":"))
    module = (
        "# Generated by mosaic_ui.foundry; do not edit by hand.\n"
        "from __future__ import annotations\n\n"
        "import json\n\n"
        f"GENERATED_ROOT = {generated_root!r}\n"
        f"PAYLOAD = json.loads({payload_json!r})\n"
    ).encode("utf-8")
    atomic_write(output_root / "library.py", module)
    atomic_write(output_root / "receipt.json", canonical_bytes({
        "schema": "mosaic.ui.foundry-receipt.v0.1",
        "input_root": input_root,
        "generated_root": generated_root,
        "module_sha256": commitment("MOSAIC.UI.GENERATED_MODULE.v0.1", module.decode("utf-8")),
        "component_count": library_validation["component_count"],
        "node_count": tree_validation["node_count"],
        "standing": "LOCAL_CANDIDATE",
        "authority_effect": "NONE",
    }) + b"\n")
    return {"generated_root": generated_root, "input_root": input_root, **library_validation, **tree_validation}


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("application", type=Path)
    args = parser.parse_args(argv)
    print(json.dumps(compile_library(args.source, args.output, args.application), indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
